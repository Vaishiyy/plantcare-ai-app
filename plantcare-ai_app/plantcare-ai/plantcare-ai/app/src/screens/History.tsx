import { useEffect, useMemo, useState } from 'react';
import { Download, History as HistoryIcon } from 'lucide-react';
import { useStore } from '../store';
import { getReadings } from '../storage/db';
import { RANGE_MS, bucketize, classSegments, dailySummary, downloadText, extremes, toCsv, type RangeKey } from '../history/aggregate';
import { TrendChart } from '../components/charts';
import { Empty, LinkBadge, fmtDateTime } from '../components/ui';
import { CLASS_INFO, PLANT_LABEL, SENSOR_META } from '../ml/interpret';
import type { PlantType, Reading, SensorKey } from '../types';

const KEYS: SensorKey[] = ['soilPct', 'humRhEst', 'sunlightPct'];
const CLASS_COLOR = { 0: 'var(--bad)', 1: 'var(--warn)', 2: 'var(--good)' } as const;
const MIN_READINGS = 3;

export function History() {
  const { source, link, settings, latest, historyVersion, toast } = useStore();
  const [range, setRange] = useState<RangeKey>('24h');
  const [plantSel, setPlantSel] = useState<PlantType | null>(null);
  const [rows, setRows] = useState<Reading[] | null>(null);
  const [loadedAt, setLoadedAt] = useState(Date.now());

  useEffect(() => {
    let cancel = false;
    const now = Date.now();
    setRows(null);
    getReadings(source, now - RANGE_MS[range], now).then((r) => {
      if (!cancel) { setRows(r); setLoadedAt(now); }
    });
    return () => { cancel = true; };
  }, [source, range, historyVersion]);

  const plantsPresent = useMemo(() => [...new Set((rows ?? []).map((r) => r.plant))], [rows]);
  const plant: PlantType = plantSel ?? latest?.plant ?? plantsPresent[0] ?? 'POTHOS';
  const pr = useMemo(() => (rows ?? []).filter((r) => r.plant === plant), [rows, plant]);
  const points = useMemo(() => bucketize(pr, range, loadedAt), [pr, range, loadedAt]);
  const coverage = points.length ? Math.round((points.filter((p) => p.soilPct !== null).length / points.length) * 100) : 0;
  const days = useMemo(() => dailySummary(pr), [pr]);
  const ext = useMemo(() => extremes(pr), [pr]);
  const segs = useMemo(() => classSegments(pr, range === '24h' ? 15 * 60000 : 60 * 60000), [pr, range]);
  const span = RANGE_MS[range];
  const startT = loadedAt - span;
  const enough = pr.length >= MIN_READINGS;
  const timeFmt = (t: number) =>
    range === '24h'
      ? new Date(t).toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' })
      : new Date(t).toLocaleDateString([], { day: 'numeric', month: 'short' });

  const exportCsv = () => {
    if (!rows?.length) { toast('Nothing to export for this period.', 'warn'); return; }
    const d = new Date().toISOString().slice(0, 10);
    downloadText(`plantcare-${source}-${range}-${d}.csv`, toCsv(rows));
    toast(`Exported ${rows.length} readings${source === 'demo' ? ' (demo data, marked in the source column)' : ''}.`, 'good');
  };

  return (
    <div className="screen-enter">
      <header className="screen-head">
        <div>
          <h1>History</h1>
          <p>{source === 'demo' ? 'Sample data generated by Demo Mode' : 'Device readings stored on this phone'}</p>
        </div>
        <LinkBadge link={link} />
      </header>

      <div className="stack">
        <div className="row wrap between">
          <div className="seg" role="group" aria-label="Time range">
            {(['24h', '7d', '30d'] as RangeKey[]).map((r) => (
              <button key={r} aria-pressed={range === r} onClick={() => setRange(r)}>{r === '24h' ? '24 hours' : r === '7d' ? '7 days' : '30 days'}</button>
            ))}
          </div>
          <button className="btn btn-soft" onClick={exportCsv} disabled={!rows?.length}><Download /> Export CSV</button>
        </div>

        <div className="row wrap">
          <div className="seg" role="group" aria-label="Plant">
            {(['ALOE_VERA', 'POTHOS'] as PlantType[]).map((p) => (
              <button key={p} aria-pressed={plant === p} onClick={() => setPlantSel(p)}>{PLANT_LABEL[p]}</button>
            ))}
          </div>
          {source === 'demo' && <span className="chip chip-demo">Sample data</span>}
        </div>

        <div className="banner banner-info">
          <HistoryIcon />
          <div>
            History is recorded only while this app is open and receiving data, because history is stored on this phone (the server also keeps a CSV log on the laptop).
            Gaps in the charts are periods with no data. Stored for {settings.retentionDays} days.
          </div>
        </div>

        {rows === null ? (
          <div className="card"><p className="muted">Loading…</p></div>
        ) : !enough ? (
          <div className="card">
            <Empty icon={<HistoryIcon />} title="Insufficient data">
              <p className="small">
                {pr.length === 0 ? `No ${PLANT_LABEL[plant]} readings` : `Only ${pr.length} ${PLANT_LABEL[plant]} reading${pr.length === 1 ? '' : 's'}`} in this period.
                Keep the app open while connected to build up history{source === 'device' ? ', or try Demo Mode to see sample charts' : ''}.
              </p>
            </Empty>
          </div>
        ) : (
          <>
            <p className="small muted">{pr.length} readings. Data covers about {coverage}% of this period.</p>

            {KEYS.map((k) => (
              <div className="card" key={k}>
                <div className="row between wrap">
                  <h3>{SENSOR_META[k].label}{k === 'humRhEst' ? ' (estimated)' : ''}</h3>
                  <span className="small muted">{SENSOR_META[k].unit}. Averaged per {range === '24h' ? '10 min' : range === '7d' ? 'hour' : '4 h'}</span>
                </div>
                <TrendChart data={points} k={k} range={settings.profiles[plant].ranges[k]} timeFmt={timeFmt} tall />
              </div>
            ))}

            <div className="card">
              <h3>Health timeline</h3>
              <p className="small muted" style={{ margin: '4px 0 10px' }}>Model class over the period. Grey means no data.</p>
              <div className="timeline-strip" role="img" aria-label="Health class over time">
                {(() => {
                  const parts: JSX.Element[] = [];
                  let cursor = startT;
                  segs.forEach((s, i) => {
                    if (s.from > cursor) parts.push(<span key={`g${i}`} style={{ flexGrow: s.from - cursor, background: 'transparent' }} />);
                    parts.push(<span key={i} title={`${CLASS_INFO[s.cls].label}: ${fmtDateTime(s.from)}`}
                      style={{ flexGrow: Math.max(s.to - s.from, span / 400), background: CLASS_COLOR[s.cls] }} />);
                    cursor = Math.max(cursor, s.to);
                  });
                  if (loadedAt > cursor) parts.push(<span key="end" style={{ flexGrow: loadedAt - cursor, background: 'transparent' }} />);
                  return parts;
                })()}
              </div>
              <div className="row between small muted" style={{ marginTop: 4 }}>
                <span>{fmtDateTime(startT)}</span><span>Now</span>
              </div>
              <div className="row wrap small" style={{ marginTop: 10, gap: 14 }}>
                {([2, 1, 0] as const).map((c) => (
                  <span className="row" style={{ gap: 6 }} key={c}><span className="class-swatch" style={{ background: CLASS_COLOR[c] }} />{CLASS_INFO[c].label}</span>
                ))}
              </div>

              <h3 style={{ marginTop: 18 }}>Condition changes</h3>
              <div className="list">
                {segs.length <= 1 ? (
                  <p className="small ink2" style={{ paddingTop: 6 }}>
                    {segs.length ? `${CLASS_INFO[segs[0].cls].label} for the whole period with data.` : 'No changes.'}
                  </p>
                ) : (
                  segs.slice(1).reverse().slice(0, 15).map((s, i, arr) => {
                    const prevIdx = segs.length - 1 - i - 1;
                    const prev = segs[prevIdx];
                    return (
                      <div className="list-item small" key={i}>
                        <b style={{ minWidth: 110 }}>{fmtDateTime(s.from)}</b>
                        <span>{prev ? `${CLASS_INFO[prev.cls].label} to ` : ''}<b>{CLASS_INFO[s.cls].label}</b></span>
                        {i === arr.length - 1 && segs.length - 1 > 15 && <span className="muted"> (older changes hidden)</span>}
                      </div>
                    );
                  })
                )}
              </div>
            </div>

            <div className="card">
              <h3>Highest and lowest</h3>
              <div className="table-wrap">
                <table className="data">
                  <thead><tr><th>Sensor</th><th className="r">Lowest</th><th>When</th><th className="r">Highest</th><th>When</th></tr></thead>
                  <tbody>
                    {KEYS.map((k) => (
                      <tr key={k}>
                        <td>{SENSOR_META[k].label}</td>
                        <td className="r"><b>{ext[k].lo?.[k] ?? '—'}</b></td><td className="muted">{fmtDateTime(ext[k].lo?.ts)}</td>
                        <td className="r"><b>{ext[k].hi?.[k] ?? '—'}</b></td><td className="muted">{fmtDateTime(ext[k].hi?.ts)}</td>
                      </tr>
                    ))}
                  </tbody>
                </table>
              </div>
            </div>

            <div className="card">
              <h3>Daily averages</h3>
              <p className="small muted" style={{ margin: '4px 0 6px' }}>Average with min–max in brackets. Only days with data are listed.</p>
              <div className="table-wrap">
                <table className="data">
                  <thead><tr><th>Day</th><th className="r">Readings</th><th className="r">Soil %</th><th className="r">Humidity %RH</th><th className="r">Light (raw)</th></tr></thead>
                  <tbody>
                    {days.map((d) => (
                      <tr key={d.day}>
                        <td>{new Date(d.day + 'T12:00').toLocaleDateString([], { weekday: 'short', day: 'numeric', month: 'short' })}</td>
                        <td className="r">{d.count}</td>
                        {KEYS.map((k) => (
                          <td className="r" key={k}><b>{Math.round(d.stats[k].avg)}</b> <span className="muted">({d.stats[k].min}–{d.stats[k].max})</span></td>
                        ))}
                      </tr>
                    ))}
                  </tbody>
                </table>
              </div>
            </div>
          </>
        )}
      </div>
    </div>
  );
}
